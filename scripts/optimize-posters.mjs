/**
 * Converts the downloaded JPEG posters into small WebP files and generates
 * tiny inline placeholders (LQIP) used while the full image loads.
 *
 * Run: npm run posters:optimize
 *
 * The placeholders are written to apps/web/src/data/placeholders.ts and the
 * poster map is updated to point at the .webp files.
 */
import sharp from 'sharp';
import { readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';

const POSTER_DIR = path.resolve('apps/web/public/posters');
const MAP_FILE = path.resolve('apps/web/src/data/posters.ts');
const PLACEHOLDER_FILE = path.resolve('apps/web/src/data/placeholders.ts');

const WIDTH = 560;
const WEBP_QUALITY = 72;
const PLACEHOLDER_WIDTH = 32;
const PLACEHOLDER_QUALITY = 32;

const jpgs = (await readdir(POSTER_DIR)).filter((file) => file.endsWith('.jpg'));
const placeholders = {};
const converted = [];

for (const file of jpgs) {
  const id = file.replace(/\.jpg$/, '');
  const source = path.join(POSTER_DIR, file);
  const buffer = await readFile(source);

  await sharp(buffer)
    .resize({ width: WIDTH, withoutEnlargement: true })
    .webp({ quality: WEBP_QUALITY, effort: 5 })
    .toFile(path.join(POSTER_DIR, `${id}.webp`));

  const tiny = await sharp(buffer)
    .resize({ width: PLACEHOLDER_WIDTH })
    .blur(1.2)
    .webp({ quality: PLACEHOLDER_QUALITY, effort: 5 })
    .toBuffer();

  placeholders[id] = `data:image/webp;base64,${tiny.toString('base64')}`;
  converted.push(source);
  console.log(`  ✓ ${id}.webp (${tiny.length} B placeholder)`);
}

for (const source of converted) {
  await unlink(source);
}

const banner = `/**
 * Generated by \`npm run posters:optimize\`. Safe to edit by hand.
 *
 * Tiny inline previews shown while a card's full poster downloads. Keeping
 * these in the bundle makes the feed look instant on slow connections.
 */`;
await writeFile(
  PLACEHOLDER_FILE,
  `${banner}\nexport const POSTER_PLACEHOLDERS: Record<string, string> = ${JSON.stringify(
    placeholders,
    null,
    2,
  )};\n`,
);

const map = await readFile(MAP_FILE, 'utf8');
await writeFile(MAP_FILE, map.replace(/\.jpg"/g, '.webp"'));

console.log(`\nWrote ${jpgs.length} WebP posters and ${jpgs.length} placeholders.`);
