/**
 * Downloads a poster screenshot for every site into apps/web/public/posters/
 * and regenerates apps/web/src/data/posters.ts.
 *
 * Run: npm run posters
 *
 * Uses WordPress' free mShots service. The first request for a URL triggers
 * generation and may return a "Generating Preview…" placeholder, so the script
 * detects duplicate images and retries them a few times.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { SITES } from '../apps/web/src/data/sites.ts';

const WIDTH = 640;
const OUT_DIR = path.resolve('apps/web/public/posters');
const MAP_FILE = path.resolve('apps/web/src/data/posters.ts');
const CONCURRENCY = 5;
const ROUNDS = 4;
const RETRY_DELAY_MS = 20000;

const hashOf = (buffer) => createHash('sha256').update(buffer).digest('hex');

async function download(site) {
  const height = Math.min(900, Math.max(420, Math.round(WIDTH / site.ratio)));
  const url = `https://s0.wp.com/mshots/v1/${encodeURIComponent(site.url)}?w=${WIDTH}&h=${height}`;

  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const response = await fetch(url, { redirect: 'follow' });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const buffer = Buffer.from(await response.arrayBuffer());
      if (buffer.length < 4000) throw new Error('response too small');
      return { buffer, hash: hashOf(buffer) };
    } catch (error) {
      if (attempt === 3) {
        console.warn(`  ! ${site.id}: ${error.message}`);
        return null;
      }
      await wait(attempt * 2000);
    }
  }
  return null;
}

function wait(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function runPool(items, worker, size) {
  const queue = [...items];
  const results = [];
  const workers = Array.from({ length: size }, async () => {
    while (queue.length) {
      const item = queue.shift();
      if (item) results.push(await worker(item));
    }
  });
  await Promise.all(workers);
  return results;
}

await mkdir(OUT_DIR, { recursive: true });

const pending = SITES.filter((site) => !site.poster);
const customCount = SITES.length - pending.length;
if (customCount > 0) {
  console.log(`Skipping ${customCount} site(s) with a custom poster.`);
}

/** @type {Map<string, { site: any, buffer: Buffer, hash: string }>} */
const results = new Map();

console.log(`Fetching ${pending.length} posters…`);
const firstPass = await runPool(
  pending,
  async (site) => ({ site, ...(await download(site)) }),
  CONCURRENCY,
);

for (const result of firstPass) {
  if (result.buffer) results.set(result.site.id, result);
}

for (let round = 1; round < ROUNDS; round += 1) {
  const counts = new Map();
  for (const { hash } of results.values()) {
    counts.set(hash, (counts.get(hash) ?? 0) + 1);
  }

  const duplicates = [...results.values()]
    .filter((entry) => counts.get(entry.hash) > 1)
    .map((entry) => entry.site);

  if (duplicates.length === 0) break;

  console.log(
    `Round ${round}: ${duplicates.length} placeholder/duplicate images — retrying in ${
      RETRY_DELAY_MS / 1000
    }s…`,
  );
  await wait(RETRY_DELAY_MS);

  const retried = await runPool(
    duplicates,
    async (site) => ({ site, ...(await download(site)) }),
    CONCURRENCY,
  );

  for (const result of retried) {
    if (!result.buffer) continue;
    const previous = results.get(result.site.id);
    if (!previous || previous.hash !== result.hash) {
      results.set(result.site.id, result);
    }
  }
}

const mapping = {};

for (const site of SITES) {
  if (site.poster) continue;
  const result = results.get(site.id);
  if (!result) {
    console.warn(`  ! ${site.id}: no poster, keeping the gradient fallback`);
    continue;
  }
  const file = path.join(OUT_DIR, `${site.id}.jpg`);
  await writeFile(file, result.buffer);
  mapping[site.id] = `/posters/${site.id}.jpg`;
  console.log(`  ✓ ${site.id}.jpg (${Math.round(result.buffer.length / 1024)} KB)`);
}

const banner = `/**
 * Generated by \`npm run posters\`. Safe to edit by hand.
 *
 * Maps a site id to a local poster in apps/web/public/.
 * Remove an entry (or the file) to fall back to a live screenshot.
 */`;
const body = `export const LOCAL_POSTERS: Record<string, string> = ${JSON.stringify(
  mapping,
  null,
  2,
)};
`;

await writeFile(MAP_FILE, `${banner}\n${body}`);

console.log(`\nWrote ${Object.keys(mapping).length}/${SITES.length} posters.`);
console.log(`Updated ${path.relative(process.cwd(), MAP_FILE)}.`);
