/**
 * Reads X-Frame-Options and CSP `frame-ancestors` for every curated site and
 * writes apps/web/src/data/embedStatus.ts.
 *
 * Run: npm run health
 *
 * Builds run this in --soft mode: it skips when the manifest is younger than a
 * day and never fails the build, so an offline machine keeps the last result.
 *
 * Why a build step: a browser cannot see response headers cross-origin, and a
 * framed site that refuses embedding still fires `load`, so this is the only
 * reliable way to know a site will actually render inside Engage.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { SITES } from '../apps/web/src/data/sites.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = path.join(ROOT, 'apps/web/src/data/embedStatus.ts');
const CONCURRENCY = 6;
const TIMEOUT_MS = 8000;
const FRESH_MS = 24 * 60 * 60 * 1000;
const SOFT = process.argv.includes('--soft');

/** Origins we are allowed to be framed by: production and local dev. */
const OUR_ORIGINS = new Set([
  'https://sitehub.sites',
  'https://www.sitehub.sites',
  'http://localhost:4000',
  'http://127.0.0.1:4000',
]);

/** Returns a human-readable refusal reason, or null when framing is allowed. */
function refusalReason(xfo, csp) {
  const x = (xfo ?? '').trim().toLowerCase();
  if (x === 'deny' || x === 'sameorigin' || x.startsWith('allow-from')) {
    return `x-frame-options: ${x}`;
  }

  const match = (csp ?? '').match(/(?:^|;)\s*frame-ancestors\s+([^;]+)/i);
  if (!match) return null;

  const sources = match[1].trim().toLowerCase().split(/\s+/);
  if (sources.includes('*')) return null;
  if (sources.some((source) => OUR_ORIGINS.has(source))) return null;
  return `frame-ancestors: ${match[1].trim()}`;
}

async function checkSite(site) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const response = await fetch(site.url, {
      redirect: 'follow',
      signal: controller.signal,
      headers: {
        // Some hosts reject unknown clients; look like a normal browser.
        'user-agent':
          'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36 SiteHubEmbedCheck',
        accept: 'text/html,application/xhtml+xml',
      },
    });

    // Only the headers matter; stop the body download immediately.
    response.body?.cancel().catch(() => {});

    if (response.status === 404 || response.status === 410) {
      return { embeddable: false, reason: `http ${response.status}` };
    }
    if (!response.ok) {
      console.warn(`  ? ${site.id}: HTTP ${response.status} (kept as unknown)`);
      return null;
    }

    const reason = refusalReason(
      response.headers.get('x-frame-options'),
      response.headers.get('content-security-policy'),
    );
    return reason ? { embeddable: false, reason } : { embeddable: true };
  } catch (error) {
    console.warn(`  ? ${site.id}: ${error.name === 'AbortError' ? 'timeout' : error.message}`);
    return null;
  } finally {
    clearTimeout(timer);
  }
}

async function readPrevious() {
  try {
    const source = await readFile(OUT_FILE, 'utf8');
    const stamp = source.match(/EMBED_STATUS_CHECKED_AT = '([^']+)'/)?.[1];
    const module = await import(pathToFileURL(OUT_FILE).href);
    return { status: module.EMBED_STATUS ?? {}, stamp };
  } catch {
    return { status: {}, stamp: undefined };
  }
}

async function main() {
  const previous = await readPrevious();

  if (SOFT && previous.stamp) {
    const age = Date.now() - Date.parse(previous.stamp);
    if (Number.isFinite(age) && age >= 0 && age < FRESH_MS) {
      console.log(
        `embed status is ${Math.round(age / 3_600_000)}h old — skipping header scan`,
      );
      return;
    }
  }

  const results = {};
  let cursor = 0;
  const workers = Array.from({ length: CONCURRENCY }, async () => {
    while (cursor < SITES.length) {
      const site = SITES[cursor];
      cursor += 1;
      const result = await checkSite(site);
      if (result) results[site.id] = result;
    }
  });
  await Promise.all(workers);

  // Keep the previous verdict for sites we could not reach this time.
  const merged = { ...previous.status, ...results };
  const ordered = {};
  for (const site of SITES) {
    if (merged[site.id]) ordered[site.id] = merged[site.id];
  }

  const checkedAt = new Date().toISOString();
  const lines = Object.entries(ordered).map(([id, value]) => {
    const reason = value.reason ? `, reason: ${JSON.stringify(value.reason)}` : '';
    return `  ${JSON.stringify(id)}: { embeddable: ${value.embeddable}${reason} },`;
  });

  const source = `/**
 * Generated by \`npm run health\` (scripts/check-embeddable.mjs).
 * Do not edit by hand.
 *
 * A site is marked non-embeddable when its response headers forbid framing
 * (X-Frame-Options, or a CSP frame-ancestors list without our origin).
 */
export interface EmbedStatus {
  embeddable: boolean;
  reason?: string;
}

export const EMBED_STATUS_CHECKED_AT = '${checkedAt}';

export const EMBED_STATUS: Record<string, EmbedStatus> = {
${lines.join('\n')}
};
`;

  await writeFile(OUT_FILE, source, 'utf8');

  const blocked = Object.values(ordered).filter((value) => !value.embeddable).length;
  console.log(
    `embed status: ${Object.keys(ordered).length}/${SITES.length} sites checked, ${blocked} non-embeddable`,
  );
}

main().catch((error) => {
  if (SOFT) {
    console.warn(`embed scan skipped: ${error.message}`);
    return;
  }
  console.error(error);
  process.exitCode = 1;
});
